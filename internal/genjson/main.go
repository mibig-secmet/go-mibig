// Command genjson writes json_gen.go: the MarshalJSON and UnmarshalJSON
// methods of all schema structs, which delegate to the object codec.
//
// A schema struct is a struct type with a field of type Extras. Methods that
// a type declares itself are not generated. Run it with go generate in the
// package directory.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

const output = "json_gen.go"

func main() {
	log.SetFlags(0)
	log.SetPrefix("genjson: ")
	dir := "."
	if len(os.Args) > 1 {
		dir = os.Args[1]
	}
	src, err := generate(dir)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, output), src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// generate returns the contents of json_gen.go for the package in dir.
func generate(dir string) ([]byte, error) {
	files, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, err
	}
	fset := token.NewFileSet()
	var types []string
	// handwritten holds the declared methods, as "Type.Method".
	handwritten := map[string]bool{}
	pkg := ""
	for _, name := range files {
		base := filepath.Base(name)
		if strings.HasSuffix(base, "_test.go") || base == output {
			continue
		}
		file, err := parser.ParseFile(fset, name, nil, parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}
		pkg = file.Name.Name
		for _, decl := range file.Decls {
			switch decl := decl.(type) {
			case *ast.FuncDecl:
				if decl.Recv != nil && (decl.Name.Name == "MarshalJSON" || decl.Name.Name == "UnmarshalJSON") {
					handwritten[receiverName(decl.Recv.List[0].Type)+"."+decl.Name.Name] = true
				}
			case *ast.GenDecl:
				for _, spec := range decl.Specs {
					ts, ok := spec.(*ast.TypeSpec)
					if !ok || ts.TypeParams != nil {
						continue
					}
					if st, ok := ts.Type.(*ast.StructType); ok && hasExtras(st) {
						types = append(types, ts.Name.Name)
					}
				}
			}
		}
	}
	if pkg == "" {
		return nil, fmt.Errorf("no Go files in %s", dir)
	}
	slices.Sort(types)

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by internal/genjson; DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "package %s\n\n", pkg)
	fmt.Fprintf(&buf, "// The JSON methods of all schema structs. They delegate to the object codec in\n")
	fmt.Fprintf(&buf, "// codec.go, which also writes and checks the discriminators of classes,\n")
	fmt.Fprintf(&buf, "// modules and domains.\n")
	for _, name := range types {
		marshal, unmarshal := !handwritten[name+".MarshalJSON"], !handwritten[name+".UnmarshalJSON"]
		if marshal || unmarshal {
			buf.WriteString("\n")
		}
		if marshal {
			fmt.Fprintf(&buf, "func (x %s) MarshalJSON() ([]byte, error) { return encodeObject(x) }\n", name)
		}
		if unmarshal {
			fmt.Fprintf(&buf, "func (x *%s) UnmarshalJSON(data []byte) error { return decodeObject(data, x) }\n", name)
		}
	}
	return format.Source(buf.Bytes())
}

// hasExtras reports whether the struct has a field of type Extras.
func hasExtras(st *ast.StructType) bool {
	for _, field := range st.Fields.List {
		if ident, ok := field.Type.(*ast.Ident); ok && ident.Name == "Extras" {
			return true
		}
	}
	return false
}

// receiverName returns the type name of a method receiver.
func receiverName(expr ast.Expr) string {
	if star, ok := expr.(*ast.StarExpr); ok {
		expr = star.X
	}
	if ident, ok := expr.(*ast.Ident); ok {
		return ident.Name
	}
	return ""
}
